export function expandSynonyms(normalizedQuery: string): readonly string[] {
  const out = new Set<string>([normalizedQuery]);
  for (const group of SYNONYM_GROUPS) {
    if (group.some((term) => term === normalizedQuery || normalizedQuery.includes(term))) {
      for (const term of group) out.add(term);
    }
  }
  return [...out];
}
