// Bundles the Bridge client (src/client/entry.ts) into the string the Vite plugin serves (R-BR-05).
// `pnpm --filter @reactcraft/bridge build` rewrites src/client/bridge-client.generated.ts.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

import { build } from 'rolldown';

const ENTRY = fileURLToPath(new URL('../src/client/entry.ts', import.meta.url));
const GENERATED_FILE = fileURLToPath(
  new URL('../src/client/bridge-client.generated.ts', import.meta.url),
);

export async function buildClientCode(): Promise<string> {
  const result = await build({
    input: ENTRY,
    write: false,
    platform: 'browser',
    output: { format: 'esm', minify: true },
  });
  return result.output[0].code;
}

export function generatedModule(code: string): string {
  return [
    '// Generated by scripts/build-client.ts from src/client/entry.ts. Do not edit.',
    `export const BRIDGE_CLIENT_CODE = ${JSON.stringify(code)};`,
    '',
  ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(GENERATED_FILE, generatedModule(await buildClientCode()));
}
