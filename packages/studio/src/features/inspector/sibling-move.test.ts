// Tests for siblingMoveTarget (Scenario #17, SPEC-04 R-SE-24).
import type { TreeNode } from '@kumicraft/shared';
import { describe, expect, it } from 'vitest';

import { siblingMoveTarget } from './sibling-move.ts';

function makeNode(overrides: Partial<TreeNode> = {}): TreeNode {
  return {
    ref: { loc: 'src/Page.tsx:10:5', index: 0 },
    tag: 'div',
    instances: 1,
    parent: 0,
    ...overrides,
  };
}

describe('siblingMoveTarget [Scenario #17]', () => {
  it('returns undefined for up when element is the first sibling', () => {
    const n1 = makeNode({ ref: { loc: 'src/Page.tsx:10:5', index: 0 }, tag: 'h1' });
    const n2 = makeNode({ ref: { loc: 'src/Page.tsx:15:5', index: 0 }, tag: 'p' });
    const tree = [n1, n2];

    const target = siblingMoveTarget(tree, n1.ref, 'up');
    expect(target).toBeUndefined();
  });

  it('ignores siblings from different files', () => {
    const n1 = makeNode({ ref: { loc: 'src/Page.tsx:10:5', index: 0 }, tag: 'div' });
    const n2 = makeNode({ ref: { loc: 'src/Header.tsx:5:5', index: 0 }, tag: 'header' });
    const tree = [n1, n2];

    const target = siblingMoveTarget(tree, n1.ref, 'down');
    expect(target).toBeUndefined();
  });

  it('ignores siblings with identical loc generated by .map loops', () => {
    const loopItem0 = makeNode({
      ref: { loc: 'src/List.tsx:20:7', index: 0 },
      tag: 'li',
    });
    const loopItem1 = makeNode({
      ref: { loc: 'src/List.tsx:20:7', index: 1 },
      tag: 'li',
    });
    const footer = makeNode({
      ref: { loc: 'src/List.tsx:30:7', index: 0 },
      tag: 'div',
    });
    const tree = [loopItem0, loopItem1, footer];

    const targetDown = siblingMoveTarget(tree, loopItem0.ref, 'down');
    expect(targetDown).toEqual({
      kind: 'sibling',
      ref: { loc: 'src/List.tsx:30:7', tag: 'div' },
      where: 'after',
    });

    const targetUp = siblingMoveTarget(tree, loopItem1.ref, 'up');
    expect(targetUp).toBeUndefined();
  });

  it('returns next sibling for down and previous sibling for up', () => {
    const a = makeNode({ ref: { loc: 'src/Page.tsx:10:5', index: 0 }, tag: 'h1' });
    const b = makeNode({ ref: { loc: 'src/Page.tsx:20:5', index: 0 }, tag: 'p' });
    const c = makeNode({ ref: { loc: 'src/Page.tsx:30:5', index: 0 }, tag: 'button' });
    const tree = [a, b, c];

    const targetDown = siblingMoveTarget(tree, a.ref, 'down');
    expect(targetDown).toEqual({
      kind: 'sibling',
      ref: { loc: 'src/Page.tsx:20:5', tag: 'p' },
      where: 'after',
    });

    const targetUp = siblingMoveTarget(tree, c.ref, 'up');
    expect(targetUp).toEqual({
      kind: 'sibling',
      ref: { loc: 'src/Page.tsx:20:5', tag: 'p' },
      where: 'before',
    });
  });
});
