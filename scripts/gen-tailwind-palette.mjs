import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const themePath = resolve('packages/studio/node_modules/tailwindcss/theme.css');
const outputPath = resolve('packages/shared/src/tailwind/palette.generated.ts');

const content = readFileSync(themePath, 'utf8');
const lines = content.split(/\r?\n/);

const colors = [];
const colorRegex = /^ {2}--color-([a-z0-9-]+):\s*([^;]+);$/;

for (const line of lines) {
  const match = colorRegex.exec(line);
  if (match) {
    const [, name, value] = match;
    colors.push({ name, value: value.trim() });
  }
}

const header =
  '// Generated by scripts/gen-tailwind-palette.mjs from tailwindcss/theme.css. Do not edit.\n';
const items = colors
  .map((c) => `  { name: ${JSON.stringify(c.name)}, value: ${JSON.stringify(c.value)} },`)
  .join('\n');
const body = `export const TAILWIND_COLORS: readonly { readonly name: string; readonly value: string }[] = [\n${items}\n];\n`;

writeFileSync(outputPath, header + body, 'utf8');
console.log(`Generated ${colors.length} Tailwind colors into ${outputPath}`);
